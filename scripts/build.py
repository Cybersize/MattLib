"""Deterministic, dependency-aware Luau bundle. No third-party packages required."""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src"
IMPORT = re.compile(r"\brequire\((script(?:\.[A-Za-z_][A-Za-z_0-9]*)*)\)")

def sources():
    modules = {}
    for path in sorted(SOURCE.rglob("*.luau")):
        relative = path.relative_to(SOURCE).with_suffix("")
        parts = list(relative.parts)
        if parts[-1] == "init":
            parts.pop()
        module_id = "/".join(parts) or "init"
        if module_id in modules:
            raise ValueError(f"Duplicate source module {module_id}")
        modules[module_id] = (path, parts, path.read_text(encoding="utf-8"))
    return modules

def bundle():
    modules = sources()
    transformed, graph = {}, {}
    for module_id, (path, parts, source) in modules.items():
        dependencies = []
        def resolve(match):
            target = parts.copy()
            for segment in match[1].split(".")[1:]:
                if segment == "Parent":
                    if not target:
                        raise ValueError(f"Import escapes src: {path}: {match[0]}")
                    target.pop()
                else:
                    target.append(segment)
            name = "/".join(target) or "init"
            if name not in modules:
                raise ValueError(f"Unresolved import {match[0]} in {path}")
            dependencies.append(name)
            return f"__require({json.dumps(name)})"
        rewritten = IMPORT.sub(resolve, source)
        if re.search(r"\brequire\s*\(", rewritten):
            raise ValueError(f"Dynamic/unsupported require in {path}")
        transformed[module_id] = rewritten
        graph[module_id] = dependencies
    ordered, visiting, visited = [], set(), set()
    def visit(name):
        if name in visiting:
            raise ValueError(f"Cyclic import at {name}")
        if name in visited:
            return
        visiting.add(name)
        for dependency in graph[name]:
            visit(dependency)
        visiting.remove(name)
        visited.add(name)
        ordered.append(name)
    visit("init")
    digest = hashlib.sha256("\n".join(name + transformed[name] for name in ordered).encode()).hexdigest()
    lines = ["--!nonstrict", "-- MattLib 1.0.0 | Generated by scripts/build.py; edit src/, not this file.",
             f"-- Source SHA-256: {digest}", "local __modules, __cache, __loading = {}, {}, {}",
             "local function __require(id)", "\tif __cache[id] ~= nil then return __cache[id] end",
             '\tassert(__modules[id], "Unknown bundled module: " .. id)',
             '\tassert(not __loading[id], "Cyclic bundled module: " .. id)',
             "\t__loading[id] = true", "\tlocal value = __modules[id](__require)",
             "\t__loading[id] = nil", "\t__cache[id] = value", "\treturn value", "end"]
    for name in ordered:
        lines += [f"\n-- BEGIN {name}", f"__modules[{json.dumps(name)}] = function(__require)",
                  transformed[name], "end", f"-- END {name}"]
    lines.append('\nreturn __require("init")\n')
    text = "\n".join(lines)
    manifest = {"version": "1.0.0", "source_sha256": digest, "bundle_sha256": hashlib.sha256(text.encode()).hexdigest(),
                "modules": len(ordered), "bytes": len(text.encode()), "dependencies": graph}
    return text, manifest

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, manifest = bundle()
    destination = ROOT / "dist" / "Library.lua"
    named_destination = ROOT / "dist" / "MattLib.lua"
    manifest_path = ROOT / "dist" / "manifest.json"
    manifest_text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != text or not named_destination.exists() or named_destination.read_text(encoding="utf-8") != text or manifest_path.read_text() != manifest_text:
            raise SystemExit("Distribution is stale; run python scripts/build.py")
        print(f"Verified deterministic bundle: {manifest['modules']} modules, {manifest['bytes']:,} bytes")
    else:
        destination.parent.mkdir(exist_ok=True)
        destination.write_text(text, encoding="utf-8", newline="\n")
        named_destination.write_text(text, encoding="utf-8", newline="\n")
        manifest_path.write_text(manifest_text, encoding="utf-8", newline="\n")
        print(f"Built {destination}: {manifest['modules']} modules, {manifest['bytes']:,} bytes")

if __name__ == "__main__":
    main()
